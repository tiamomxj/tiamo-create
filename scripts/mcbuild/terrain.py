def _align(box, step):
    x0, y0, z0, x1, y1, z1 = box
    f = lambda v: (v // step) * step
    c = lambda v: -((-v) // step) * step
    return f(x0), f(y0), f(z0), c(x1), c(y1), c(z1)


def extract_voxy(store_path, box, cache_dir, voxy_jar=None) -> Site:
    from .vendor.atlas.voxy import Store, runtime_for, section_key, decode_section
    store_path = Path(store_path)
    x0, y0, z0, x1, y1, z1 = _align(box, 32)
    store = Store(store_path, runtime_for(store_path, Path(cache_dir) / 'voxy-runtime', voxy_jar))
    log('voxy', store.label, 'maxLevel', store.max_level, 'sections', len(store.keys))
    shape = (y1 - y0, z1 - z0, x1 - x0)
    ids = np.full(shape, MISSING, np.uint32)
    biomes = np.zeros(shape, np.uint16)
    keys, where = [], []
    for sy in range(y0 // 32, y1 // 32):
        for sz in range(z0 // 32, z1 // 32):
            for sx in range(x0 // 32, x1 // 32):
                keys.append(section_key(0, sx, sy, sz)); where.append((sx, sy, sz))
    found = 0
    for i in range(0, len(keys), 512):
        for key, (sx, sy, sz), blob in zip(keys[i:i + 512], where[i:i + 512], store.db.get_many(keys[i:i + 512])):
            if not blob:
                continue
            vox, _ = decode_section(blob, key)
            sl = np.s_[sy * 32 - y0:sy * 32 - y0 + 32, sz * 32 - z0:sz * 32 - z0 + 32, sx * 32 - x0:sx * 32 - x0 + 32]
            ids[sl] = ((vox >> np.uint64(27)) & np.uint64(0xFFFFF)).astype(np.uint32)
            biomes[sl] = ((vox >> np.uint64(47)) & np.uint64(511)).astype(np.uint16)
            found += 1
    log('L0 sections', found, '/', len(keys), '(missing sections = never visited / not cached)')
    used = sorted(int(v) for v in np.unique(ids) if v != MISSING)
    states = {str(i): store.states.get(i, {'Name': 'minecraft:barrier'}) for i in used}
    bnames = {str(b): store.biomes.get(b, '?') for b in sorted(int(v) for v in np.unique(biomes))}
    store.db.close()
    return Site(ids, biomes, (x0, y0, z0), states, bnames,
                {'kind': 'voxy', 'store': str(store_path), 'sectionsFound': found, 'sectionsTotal': len(keys)})


def extract_anvil(world_path, box, dimension='overworld') -> Site:
    from .vendor.atlas.anvil import World
    w = World(world_path)
    x0, y0, z0, x1, y1, z1 = _align(box, 16)
    shape = (y1 - y0, z1 - z0, x1 - x0)
    ids = np.full(shape, MISSING, np.uint32)
    biomes = np.zeros(shape, np.uint16)
    gid, states, bid, bnames = {}, {}, {}, {}
    n = 0
    for cz in range(z0 // 16, z1 // 16):
        for cx in range(x0 // 16, x1 // 16):
            c = w.chunk(dimension, cx, cz)
            if c is None:
                continue
            n += 1
            lut = np.zeros(len(c.states), np.uint32)
            for i, s in enumerate(c.states):
                key = s['Name'] + json.dumps(s.get('Properties', {}), sort_keys=True)
                if key not in gid:
                    gid[key] = len(gid); states[str(gid[key])] = {'Name': s['Name'], **({'Properties': s['Properties']} if s.get('Properties') else {})}
                lut[i] = gid[key]
            ya, yb = max(y0, c.y0), min(y1, c.y0 + len(c.blocks))
            if ya >= yb:
                continue
            xs, zs = cx * 16 - x0, cz * 16 - z0
            ids[ya - y0:yb - y0, zs:zs + 16, xs:xs + 16] = lut[c.blocks[ya - c.y0:yb - c.y0]]
            for sy, (bp, arr) in c.biomes.items():
                for b in bp:
                    if b not in bid:
                        bid[b] = len(bid); bnames[str(bid[b])] = b
                lo, hi = max(ya, sy * 16), min(yb, sy * 16 + 16)
                if lo >= hi:
                    continue
                sub = np.vectorize(lambda i: bid[bp[i]] if i < len(bp) else 0)(arr)          # [4y, 4z, 4x]
                full = sub.repeat(4, 0).repeat(4, 1).repeat(4, 2)
                biomes[lo - y0:hi - y0, zs:zs + 16, xs:xs + 16] = full[lo - sy * 16:hi - sy * 16]
    log('anvil', w.name, 'chunks read', n)
    return Site(ids, biomes, (x0, y0, z0), states, bnames, {'kind': 'anvil', 'world': str(world_path), 'name': w.name, 'dimension': dimension})


def make_flat(box, ground_y=64, top='grass_block[snowy=false]', layers=(('dirt', 3),), base='stone', water_y=None,
              biome='minecraft:plains') -> Site:
    x0, y0, z0, x1, y1, z1 = box
    shape = (y1 - y0, z1 - z0, x1 - x0)
    pal = {'0': {'Name': 'minecraft:air'}}
    def pid(spec):
        st = make(*_split(spec))
        for k, v in pal.items():
            if v == st.nbt():
                return int(k)
        pal[str(len(pal))] = st.nbt()
        return len(pal) - 1
    ids = np.zeros(shape, np.uint32)
    y = ground_y
    ids[max(0, y - y0):max(0, y - y0 + 1)] = pid(top)
    for spec, n in layers:
        for _ in range(n):
            y -= 1
            if y >= y0:
                ids[y - y0] = pid(spec)
    if y - y0 > 0:
        ids[:y - y0] = pid(base)
    if water_y is not None and water_y > ground_y:
        ids[ground_y - y0 + 1:water_y - y0 + 1] = pid('water[level=0]')
    return Site(ids, np.zeros(shape, np.uint16), (x0, y0, z0), pal, {'0': biome},
                {'kind': 'flat', 'ground_y': ground_y, 'top': top, 'water_y': water_y})


def _split(spec):
    if '[' in spec:
        name, rest = spec.split('[', 1)
        return name, dict(p.split('=', 1) for p in rest.rstrip(']').split(',') if p)
    return spec, {}


def extract_schematic(path, origin=(0, 0, 0), margin=0) -> Site:
    """Surroundings given as a schematic file (litematic / Sponge schem / vanilla structure nbt)."""
    from .schematic import read_any
    cells = read_any(path)               # {(x, y, z): State} in schematic coordinates
    ox, oy, oz = origin
    xs = [p[0] for p in cells]; ys = [p[1] for p in cells]; zs = [p[2] for p in cells]
    x0, y0, z0 = min(xs) + ox - margin, min(ys) + oy, min(zs) + oz - margin
    x1, y1, z1 = max(xs) + ox + 1 + margin, max(ys) + oy + 1 + margin, max(zs) + oz + 1 + margin
    ids = np.full((y1 - y0, z1 - z0, x1 - x0), MISSING, np.uint32)
    pal, gid = {}, {}
    for (x, y, z), st in cells.items():
        k = st.key()
        if k not in gid:
            gid[k] = len(gid); pal[str(gid[k])] = st.nbt()
        ids[y + oy - y0, z + oz - z0, x + ox - x0] = gid[k]
    return Site(ids, np.zeros(ids.shape, np.uint16), (x0, y0, z0), pal, {'0': 'minecraft:plains'},
                {'kind': 'schematic', 'file': str(path), 'origin': list(origin)})


