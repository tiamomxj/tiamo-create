def _dir_size_mb(p):
    try:
        return round(sum(f.stat().st_size for f in Path(p).iterdir() if f.is_file()) / 1e6, 1)
    except OSError:
        return 0


def discover(roots=None, limit_saves=40):
    """Everything readable on this machine that can provide terrain, locations or references, per game folder:
    Voxy caches (per server / dimension), Bobby chunk caches, singleplayer saves (+ player position), Xaero
    waypoints, Litematica schematics, recent screenshots and the mods that matter (Litematica, Voxy, Bobby ...)."""
    from .util import game_dirs
    from .vendor.atlas.anvil import read_nbt
    import glob, gzip
    out = {'gameDirs': [], 'voxy': [], 'bobby': [], 'saves': [], 'waypoints': [], 'schematics': [], 'screenshots': []}
    for g in (roots or game_dirs()):
        g = Path(g)
        mods = [p.name.lower() for p in g.glob('mods/*.jar')]

        def has(*keys):
            return any(any(k in m for k in keys) for m in mods)
        out['gameDirs'].append({'path': str(g), 'version': guess_version(g), 'saves': len(list(g.glob('saves/*/level.dat'))),
                                'litematica': has('litematica'), 'voxy': has('voxy'), 'bobby': has('bobby'),
                                'xaero': has('xaero'), 'distantHorizons': has('distanthorizons', 'distant-horizons')})
        for st in glob.glob(str(g / '.voxy' / 'saves' / '*' / '*' / 'storage')):
            st = Path(st)
            out['voxy'].append({'gameDir': str(g), 'server': st.parent.parent.name, 'dimHash': st.parent.name, 'store': str(st),
                                'sizeMB': _dir_size_mb(st)})
        if (g / '.bobby').is_dir():
            for d in sorted({p.parent for p in (g / '.bobby').glob('**/*.mca')}):
                rel = d.relative_to(g / '.bobby').parts
                out['bobby'].append({'gameDir': str(g), 'server': rel[0] if rel else '?', 'dimension': '/'.join(rel[-2:]),
                                     'folder': str(d), 'regions': len(list(d.glob('*.mca'))), 'sizeMB': _dir_size_mb(d)})
        for lvl in glob.glob(str(g / 'saves' / '*' / 'level.dat')):
            p = Path(lvl).parent
            info = {'gameDir': str(g), 'folder': str(p), 'name': p.name}
            try:
                d = read_nbt(gzip.decompress(Path(lvl).read_bytes())).get('Data', {})
                info['name'] = str(d.get('LevelName', p.name))
                info['version'] = str(d.get('Version', {}).get('Name', '?'))
                pl = d.get('Player', {})
                if pl.get('Pos') is not None and len(pl.get('Pos')):
                    info['playerPos'] = [round(float(v), 1) for v in pl['Pos']]
                info['lastPlayed'] = int(d.get('LastPlayed', 0))
            except Exception as e:                               # unreadable level.dat: still list it
                info['error'] = str(e)[:80]
            out['saves'].append(info)
        for wp in glob.glob(str(g / 'XaeroWaypoints' / '*' / '*' / 'mw*.txt')) + glob.glob(str(g / 'xaero' / 'minimap' / '*' / '*' / 'mw*.txt')):
            wp = Path(wp)
            for line in wp.read_text(encoding='utf-8', errors='replace').splitlines():
                if line.startswith('waypoint:'):
                    f = line.split(':')
                    try:
                        out['waypoints'].append({'world': wp.parent.parent.name, 'dim': wp.parent.name, 'name': f[1],
                                                 'x': int(f[3]), 'y': None if f[4] == '~' else int(f[4]), 'z': int(f[5])})
                    except (ValueError, IndexError):
                        pass
        sd = g / 'schematics'
        if sd.is_dir():
            files = sorted(sd.rglob('*.litematic'), key=lambda p: -p.stat().st_mtime)
            out['schematics'].append({'folder': str(sd), 'count': len(files), 'recent': [p.name for p in files[:8]]})
        if (g / 'screenshots').is_dir():
            for s_ in sorted((g / 'screenshots').glob('*.png'), key=lambda p: -p.stat().st_mtime)[:5]:
                out['screenshots'].append({'file': str(s_), 'mtime': int(s_.stat().st_mtime)})
    out['saves'].sort(key=lambda s: -s.get('lastPlayed', 0))
    out['saves'] = out['saves'][:limit_saves]
    out['screenshots'].sort(key=lambda s: -s['mtime'])
    return out


