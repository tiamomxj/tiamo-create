DIM_LABEL = {'overworld': 'overworld', 'the_nether': 'the_nether', 'nether': 'the_nether', 'the_end': 'the_end', 'end': 'the_end'}


def find_voxy_store(server=None, dimension='overworld', store=None, cache_dir=None, voxy_jar=None):
    """Pick the Voxy storage folder for a server name (substring) and dimension: the biggest matching cache."""
    if store:
        return Path(store)
    cands = [v for v in discover()['voxy'] if not server or server.lower() in v['server'].lower()]
    if not cands:
        raise SystemExit(f'no Voxy cache for server {server!r} on this machine. `mcb find-data` lists what exists; if the '
                         f'game folder is not found automatically: `mcb config add game_dirs <folder>`, or set [site] store.')
    if len(cands) == 1:
        return Path(cands[0]['store'])
    from .vendor.atlas.voxy import Store, runtime_for
    want = DIM_LABEL.get(dimension, dimension)
    best = None
    for c in cands:
        try:
            s = Store(Path(c['store']), runtime_for(Path(c['store']), Path(cache_dir or '.') / 'voxy-runtime', voxy_jar))
            label, n = s.label, len(s.keys)
            s.db.close()
        except Exception:
            continue
        if label == want and (best is None or n > best[1]):
            best = (c['store'], n)
    if not best:
        raise SystemExit(f'server {server!r} has no Voxy cache for dimension {dimension}.')
    return Path(best[0])
