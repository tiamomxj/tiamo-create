@lru_cache(maxsize=None)
def kind(st: State) -> str:
    """'air' | 'water' (water without collision: seagrass, kelp…) | 'lava' | 'plant' (no collision: grass, flowers,
    torches…) | 'light' (small light sources with collision: lanterns, candles, sea pickles) | 'solid'."""
    if st.name in ('minecraft:air', 'minecraft:cave_air', 'minecraft:void_air', 'minecraft:structure_void'):
        return 'air'
    f = facts(st)
    if not f.collides:
        if f.water:
            return 'water'
        if f.lava:
            return 'lava'
        return 'plant'
    if f.lum > 0 and not f.full_cube:
        return 'light'
    return 'solid'


@lru_cache(maxsize=None)
def is_vegetation(st: State) -> bool:
    return st.short in VEGETATION or any(in_tag(st, t) for t in VEGETATION_TAGS) or is_leaves(st)


@lru_cache(maxsize=None)
def is_natural(st: State) -> bool:
    """Generated by the world (terrain, water, plants, trees), as opposed to placed by players."""
    k = kind(st)
    if k in ('air', 'water', 'lava'):
        return True
    return (st.short in NATURAL or is_vegetation(st) or any(in_tag(st, t) for t in NATURAL_TAGS)
            or (k == 'plant' and facts(st).replaceable))


class Site:
    def __init__(self, ids, biomes, origin, states: dict, biome_names: dict | None = None, source: dict | None = None):
        self.IDS = ids
        self.biomes = biomes
        self.X0, self.Y0, self.Z0 = (int(v) for v in origin)
        self.H, self.D, self.W = ids.shape
        self._pal = states
        self.biome_names = biome_names or {}
        self.source = source or {}
        self._cache = {}

    # ---------------------------------------------------------------- io
    @classmethod
    def load(cls, art: Path):
        art = Path(art)
        if not (art / 'site.npz').exists():
            raise SystemExit(f'no terrain data {art / "site.npz"} - run `mcb site` first.')
        d = np.load(art / 'site.npz')
        pal = json.loads((art / 'site-palette.json').read_text(encoding='utf-8'))
        return cls(d['ids'], d['biomes'] if 'biomes' in d else np.zeros(d['ids'].shape, np.uint16), d['origin'],
                   pal['states'], pal.get('biomes', {}), pal.get('source', {}))

    def save(self, art: Path):
        art = Path(art); art.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(art / 'site.npz', ids=self.IDS, biomes=self.biomes, origin=np.array([self.X0, self.Y0, self.Z0]))
        used = sorted(int(v) for v in np.unique(self.IDS) if v != MISSING)
        bused = sorted(int(v) for v in np.unique(self.biomes))
        write_json(art / 'site-palette.json', {
            'states': {str(i): self._pal[str(i)] for i in used if str(i) in self._pal},
            'biomes': {str(b): self.biome_names.get(str(b), self.biome_names.get(b, '?')) for b in bused},
            'origin': [self.X0, self.Y0, self.Z0], 'size': [self.W, self.H, self.D], 'source': self.source})

    @classmethod
    def empty(cls, box, ground_y=None):
        """No known terrain (air everywhere, MISSING marks 'unknown')."""
        x0, y0, z0, x1, y1, z1 = box
        return cls(np.full((y1 - y0, z1 - z0, x1 - x0), MISSING, np.uint32), np.zeros((y1 - y0, z1 - z0, x1 - x0), np.uint16),
                   (x0, y0, z0), {}, {}, {'kind': 'none', 'ground_y': ground_y})

    # ---------------------------------------------------------------- queries
    @property
    def box(self):
        return (self.X0, self.Y0, self.Z0, self.X0 + self.W, self.Y0 + self.H, self.Z0 + self.D)

    def contains(self, x, y, z):
        return self.X0 <= x < self.X0 + self.W and self.Y0 <= y < self.Y0 + self.H and self.Z0 <= z < self.Z0 + self.D

    def state_of(self, i) -> State:
        st = self._cache.get(i)
        if st is None:
            s = self._pal.get(str(int(i)))
            st = AIR
            if s is not None:
                try:
                    st = make(s['Name'], s.get('Properties', {}))
                except (KeyError, ValueError):
                    st = AIR
            if st.short in ('cave_air', 'void_air'):
                st = AIR
            self._cache[i] = st
        return st

    def world(self, x, y, z) -> State:
        if not self.contains(x, y, z):
            return AIR
        v = int(self.IDS[y - self.Y0, z - self.Z0, x - self.X0])
        return AIR if v == MISSING else self.state_of(v)

    def known(self, x, y, z):
        return self.contains(x, y, z) and int(self.IDS[y - self.Y0, z - self.Z0, x - self.X0]) != MISSING

    kind = staticmethod(kind)

    def ground_top(self, x, z):
        """Y of the highest block that is not air / water / lava / plant / small light (trees and builds count)."""
        k = (x, z)
        g = self._cache.get(('g', k))
        if g is None:
            g = self.Y0
            for y in range(self.Y0 + self.H - 1, self.Y0 - 1, -1):
                if kind(self.world(x, y, z)) == 'solid':
                    g = y
                    break
            self._cache[('g', k)] = g
        return g

    def terrain_top(self, x, z):
        """Like ground_top but also ignoring vegetation (trees, bamboo, snow layers): the natural ground surface."""
        for y in range(self.Y0 + self.H - 1, self.Y0 - 1, -1):
            st = self.world(x, y, z)
            if kind(st) == 'solid' and not is_vegetation(st):
                return y
        return self.Y0

    def water_top(self, x, z):
        """Y of the highest water block directly above the ground, or None."""
        g = self.ground_top(x, z)
        top = None
        for y in range(g + 1, g + 40):
            if kind(self.world(x, y, z)) == 'water':
                top = y
            else:
                break
        return top

    def is_water(self, x, y, z):
        return kind(self.world(x, y, z)) == 'water'

    def biome_at(self, x, y, z):
        if not self.contains(x, y, z):
            return 'minecraft:plains'
        b = int(self.biomes[y - self.Y0, z - self.Z0, x - self.X0])
        return self.biome_names.get(str(b), 'minecraft:plains')

    # ---------------------------------------------------------------- vectorised helpers
    def palette_states(self):
        """(ids array, list of States) for all palette entries used by the grid."""
        used = [int(v) for v in np.unique(self.IDS) if v != MISSING]
        return used, [self.state_of(i) for i in used]

    def lut(self, fn, dtype=np.uint8, missing=0):
        """Vectorised per-cell property: returns fn(State) mapped over the grid via a lookup table."""
        used, states = self.palette_states()
        size = (max(used) + 2) if used else 2
        table = np.full(size, missing, dtype)
        for i, st in zip(used, states):
            table[i] = fn(st)
        ids = np.where(self.IDS == MISSING, size - 1, self.IDS).astype(np.int64)
        table[size - 1] = missing
        return table[ids]

    def heightmap(self, test=None):
        """[z, x] Y of the highest cell where test(State) is true (default: kind == 'solid'); Y0-1 where none."""
        test = test or (lambda st: kind(st) == 'solid')
        m = self.lut(lambda st: 1 if test(st) else 0).astype(bool)
        has = m.any(0)
        top = self.H - 1 - np.argmax(m[::-1], axis=0)
        return np.where(has, top + self.Y0, self.Y0 - 1)


