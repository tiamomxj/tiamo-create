"""The real (or synthetic) terrain around the build: one grid format for every data source.

artifacts/site.npz      ids [y, z, x] uint32 (palette index, MISSING = not cached / unknown), biomes, origin
artifacts/site-palette.json  {'states': {id: {Name, Properties}}, 'biomes': {id: name}, 'source': {...}}

Sources (see `extract`):
  voxy      read-only from a Voxy LOD cache (servers you have visited; L0 = exact block states)
  anvil     a Java Edition save folder (singleplayer / downloaded world / server backup) or a bare folder of region
            files (a Bobby chunk cache of a server, a region backup)
  schematic a .litematic / .schem / .nbt that holds the surroundings
  flat      synthetic ground (grass on dirt on stone, optional water) — for builds with no known site
"""
